/**
 * Reads back protocol/testvectors/{identity,devicecert}.json (generated by
 * GenerateTestVectors.kt) and re-verifies every vector through the normal public API - the
 * closed loop core/CLAUDE.md asks for before a vector PR goes to the spec repo.
 */
class TestVectorsVerificationTest {

    private fun b64(s: String): ByteArray = Base64.UrlSafe.withPadding(Base64.PaddingOption.ABSENT).decode(s)

    private fun vectors(fileName: String): JsonArray {
        val dir = System.getProperty("squaddle.testvectors") ?: error("squaddle.testvectors system property not set")
        return Json.parseToJsonElement(File(dir, fileName).readText()).jsonArray
    }

    private suspend fun crypto(): Crypto = LibsodiumCrypto.create()

    @Test
    fun cborRejectVectorsVerify() = runTest {
        for (vector in vectors("cbor-reject.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val cbor = b64(obj["input"]!!.jsonObject["cbor"]!!.jsonPrimitive.content)
            val accept = obj["expected"]!!.jsonObject["accept"]!!.jsonPrimitive.booleanOrNull!!
            if (accept) {
                CanonicalCborCodec.decode(cbor) // must not throw
            } else {
                assertFailsWith<Exception>(name) { CanonicalCborCodec.decode(cbor) }
            }
        }
    }

    @Test
    fun identityVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("identity.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject

            if (expected["accept"]?.jsonPrimitive?.booleanOrNull == false) {
                val words = input["mnemonic"]!!.jsonArray.map { it.jsonPrimitive.content }
                assertFailsWith<Bip39.InvalidMnemonicException>(name) { Bip39.fromWords(crypto, words) }
                continue
            }

            val entropy = b64(input["entropy"]!!.jsonPrimitive.content)
            val identity = UserIdentity.fromEntropy(crypto, entropy)
            assertEquals(expected["mnemonic"]!!.jsonArray.map { it.jsonPrimitive.content }, identity.toMnemonic(crypto), name)
            assertContentEquals(b64(expected["master"]!!.jsonPrimitive.content), crypto.blake2b256(entropy), name)
            assertContentEquals(b64(expected["userKey"]!!.jsonPrimitive.content), identity.userKey, name)
            assertContentEquals(b64(expected["userBoxKey"]!!.jsonPrimitive.content), identity.userBoxKey, name)
            assertContentEquals(b64(expected["backupKey"]!!.jsonPrimitive.content), identity.backupKey, name)
        }
    }

    @Test
    fun deviceCertVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("devicecert.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject
            val accept = expected["accept"]!!.jsonPrimitive.booleanOrNull!!

            if (!accept) {
                val cert = decodeDeviceCert(b64(input["cbor"]!!.jsonPrimitive.content))
                assertFalse(cert.verify(crypto), name)
                continue
            }

            val cert = decodeDeviceCert(b64(expected["cbor"]!!.jsonPrimitive.content))
            assertTrue(cert.verify(crypto), name)
            assertEquals(input["label"]!!.jsonPrimitive.content, cert.label, name)
            assertEquals(input["issuedAt"]!!.jsonPrimitive.long, cert.issuedAt, name)
            assertContentEquals(b64(input["user"]!!.jsonPrimitive.content), cert.user, name)
            assertContentEquals(b64(input["userBox"]!!.jsonPrimitive.content), cert.userBox, name)
            assertContentEquals(b64(input["device"]!!.jsonPrimitive.content), cert.device, name)
            assertContentEquals(b64(expected["sig"]!!.jsonPrimitive.content), cert.sig!!, name)
            assertContentEquals(b64(expected["unsignedCbor"]!!.jsonPrimitive.content), CanonicalCborCodec.encode(cert.toUnsignedCbor()), name)
            assertContentEquals(
                b64(expected["signingInput"]!!.jsonPrimitive.content),
                crypto.signingInput(DeviceCert.DOMAIN, CanonicalCborCodec.encode(cert.toUnsignedCbor())),
                name,
            )
        }
    }

    /** Minimal decoder for the full 0..6 field DeviceCert CBOR shape used by test-vector input. */
    private fun decodeDeviceCert(bytes: ByteArray): DeviceCert =
        decodeDeviceCertFromMap((CanonicalCborCodec.decode(bytes) as CborValue.Map).entries)

    private fun decodeDeviceCertFromMap(map: Map<Long, CborValue>): DeviceCert = DeviceCert(
        v = (map.getValue(0L) as CborValue.UInt).value.toInt(),
        user = (map.getValue(1L) as CborValue.Bytes).value,
        userBox = (map.getValue(2L) as CborValue.Bytes).value,
        device = (map.getValue(3L) as CborValue.Bytes).value,
        label = (map.getValue(4L) as CborValue.Text).value,
        issuedAt = (map.getValue(5L) as CborValue.UInt).value,
        sig = (map[6L] as? CborValue.Bytes)?.value,
    )

    /** Minimal decoder for the full 0..9 field LogEntry CBOR shape used by test-vector input. */
    private fun decodeLogEntry(bytes: ByteArray): LogEntry {
        val map = (CanonicalCborCodec.decode(bytes) as CborValue.Map).entries
        val certMap = (map.getValue(5L) as CborValue.Map).entries
        val typeCode = (map.getValue(6L) as CborValue.UInt).value.toInt()
        return LogEntry(
            v = (map.getValue(0L) as CborValue.UInt).value.toInt(),
            room = (map.getValue(1L) as CborValue.Bytes).value,
            index = (map.getValue(2L) as CborValue.UInt).value,
            prev = (map[3L] as? CborValue.Bytes)?.value,
            author = (map.getValue(4L) as CborValue.Bytes).value,
            cert = decodeDeviceCertFromMap(certMap),
            type = EntryType.entries.first { it.code == typeCode },
            body = map.getValue(7L) as CborValue.Map,
            ts = (map.getValue(8L) as CborValue.UInt).value,
            sig = (map[9L] as? CborValue.Bytes)?.value,
        )
    }

    @Test
    fun logEntryVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("logentry.json")) {
            val obj = vector.jsonObject
            val expectedRoomId = b64(obj["input"]!!.jsonObject["room"]!!.jsonPrimitive.content)
            var state: MembershipState = MembershipStateImpl.empty(crypto)
            for (entryJson in obj["expected"]!!.jsonObject["entries"]!!.jsonArray) {
                val entryObj = entryJson.jsonObject
                val entry = decodeLogEntry(b64(entryObj["cbor"]!!.jsonPrimitive.content))
                state = state.apply(StoredEntry(entry, 1_700_000_500L)).getOrThrow()
                assertContentEquals(b64(entryObj["entryHash"]!!.jsonPrimitive.content), entry.entryHash(crypto))
                assertEquals(entryObj["rotationPending"]!!.jsonPrimitive.booleanOrNull, state.rotationPending)
            }
            assertContentEquals(expectedRoomId, state.roomId)
        }
    }

    @Test
    fun logRejectVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("log-reject.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            var state: MembershipState = MembershipStateImpl.empty(crypto)
            for (prefixCbor in input["prefix"]!!.jsonArray) {
                val entry = decodeLogEntry(b64(prefixCbor.jsonPrimitive.content))
                state = state.apply(StoredEntry(entry, 1_700_000_500L)).getOrThrow()
            }
            val badEntry = decodeLogEntry(b64(input["entry"]!!.jsonPrimitive.content))
            assertTrue(state.apply(StoredEntry(badEntry, 1_700_000_500L)).isFailure, name)
        }
    }

    @Test
    fun inviteVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("invite.json")) {
            val obj = vector.jsonObject
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject
            val secret = b64(input["inviteSecret"]!!.jsonPrimitive.content)
            val roomIdBytes = b64(input["roomId"]!!.jsonPrimitive.content)
            val inviteId = b64(input["inviteId"]!!.jsonPrimitive.content)

            if (expected["accept"]!!.jsonPrimitive.booleanOrNull == false) {
                val envelope = b64(input["envelope"]!!.jsonPrimitive.content)
                assertNull(InviteEnvelope.open(crypto, secret, roomIdBytes, inviteId, envelope))
                continue
            }

            assertContentEquals(b64(expected["inviteKey"]!!.jsonPrimitive.content), InviteEnvelope.inviteKey(crypto, secret))
            val envelope = b64(expected["envelope"]!!.jsonPrimitive.content)
            val opened = InviteEnvelope.open(crypto, secret, roomIdBytes, inviteId, envelope)
            assertContentEquals(roomIdBytes, opened?.room)
            assertEquals(input["epoch"]!!.jsonPrimitive.long, opened?.epoch)
            assertContentEquals(b64(input["epochKey"]!!.jsonPrimitive.content), opened?.epochKey)
            assertEquals(input["roomName"]?.jsonPrimitive?.content, opened?.roomName)
        }
    }

    /** Minimal decoder for the full 0..8 field Snapshot CBOR shape used by test-vector input. */
    private fun decodeSnapshot(bytes: ByteArray): Snapshot {
        val map = (CanonicalCborCodec.decode(bytes) as CborValue.Map).entries
        return Snapshot(
            v = (map.getValue(0L) as CborValue.UInt).value.toInt(),
            room = (map.getValue(1L) as CborValue.Bytes).value,
            epoch = (map.getValue(2L) as CborValue.UInt).value,
            coversUpTo = (map.getValue(3L) as CborValue.UInt).value,
            nonce = (map.getValue(4L) as CborValue.Bytes).value,
            ct = (map.getValue(5L) as CborValue.Bytes).value,
            author = (map.getValue(6L) as CborValue.Bytes).value,
            device = (map.getValue(7L) as CborValue.Bytes).value,
            sig = (map[8L] as? CborValue.Bytes)?.value,
        )
    }

    @Test
    fun snapshotVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("snapshot.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject
            val accept = expected["accept"]!!.jsonPrimitive.booleanOrNull!!

            if (!accept) {
                val snapshot = decodeSnapshot(b64(input["cbor"]!!.jsonPrimitive.content))
                assertFalse(snapshot.verify(crypto), name)
                continue
            }

            val snapshot = decodeSnapshot(b64(expected["cbor"]!!.jsonPrimitive.content))
            assertTrue(snapshot.verify(crypto), name)
            assertContentEquals(b64(input["room"]!!.jsonPrimitive.content), snapshot.room, name)
            assertEquals(input["epoch"]!!.jsonPrimitive.long, snapshot.epoch, name)
            assertEquals(input["coversUpTo"]!!.jsonPrimitive.long, snapshot.coversUpTo, name)
            assertContentEquals(b64(input["nonce"]!!.jsonPrimitive.content), snapshot.nonce, name)
            assertContentEquals(b64(input["ct"]!!.jsonPrimitive.content), snapshot.ct, name)
            assertContentEquals(b64(input["author"]!!.jsonPrimitive.content), snapshot.author, name)
            assertContentEquals(b64(input["device"]!!.jsonPrimitive.content), snapshot.device, name)
            assertContentEquals(b64(expected["sig"]!!.jsonPrimitive.content), snapshot.sig!!, name)
            assertContentEquals(b64(expected["ad"]!!.jsonPrimitive.content), CanonicalCborCodec.encode(snapshot.toAdCbor()), name)
            assertContentEquals(b64(expected["unsignedCbor"]!!.jsonPrimitive.content), CanonicalCborCodec.encode(snapshot.toUnsignedCbor()), name)
            assertContentEquals(
                b64(expected["signingInput"]!!.jsonPrimitive.content),
                crypto.signingInput(Snapshot.DOMAIN, CanonicalCborCodec.encode(snapshot.toUnsignedCbor())),
                name,
            )
        }
    }

    /** Minimal decoder for the full 0..9 field OpEnvelope CBOR shape used by test-vector input. */
    private fun decodeOpEnvelope(bytes: ByteArray): OpEnvelope {
        val map = (CanonicalCborCodec.decode(bytes) as CborValue.Map).entries
        return OpEnvelope(
            v = (map.getValue(0L) as CborValue.UInt).value.toInt(),
            room = (map.getValue(1L) as CborValue.Bytes).value,
            epoch = (map.getValue(2L) as CborValue.UInt).value,
            author = (map.getValue(3L) as CborValue.Bytes).value,
            device = (map.getValue(4L) as CborValue.Bytes).value,
            seq = (map.getValue(5L) as CborValue.UInt).value,
            lamport = (map.getValue(6L) as CborValue.UInt).value,
            nonce = (map.getValue(7L) as CborValue.Bytes).value,
            ct = (map.getValue(8L) as CborValue.Bytes).value,
            sig = (map[9L] as? CborValue.Bytes)?.value,
        )
    }

    @Test
    fun opVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("op.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject
            val accept = expected["accept"]!!.jsonPrimitive.booleanOrNull!!

            if (!accept) {
                val op = decodeOpEnvelope(b64(input["cbor"]!!.jsonPrimitive.content))
                val epochKey = b64(input["epochKey"]!!.jsonPrimitive.content)
                val certs = input["certs"]!!.jsonArray.map { decodeDeviceCertFromMap((CanonicalCborCodec.decode(b64(it.jsonPrimitive.content)) as CborValue.Map).entries) }
                val result = op.open(crypto, epochKey) { device -> certs.firstOrNull { it.device.contentEquals(device) } }
                assertTrue(result is OpOpenResult.Reject, name)
                assertEquals(expected["reason"]!!.jsonPrimitive.content, result.reason, name)
                continue
            }

            val op = decodeOpEnvelope(b64(expected["cbor"]!!.jsonPrimitive.content))
            assertTrue(op.verify(crypto), name)
            assertContentEquals(b64(input["room"]!!.jsonPrimitive.content), op.room, name)
            assertEquals(input["epoch"]!!.jsonPrimitive.long, op.epoch, name)
            assertContentEquals(b64(input["author"]!!.jsonPrimitive.content), op.author, name)
            assertContentEquals(b64(input["device"]!!.jsonPrimitive.content), op.device, name)
            assertEquals(input["seq"]!!.jsonPrimitive.long, op.seq, name)
            assertEquals(input["lamport"]!!.jsonPrimitive.long, op.lamport, name)
            assertContentEquals(b64(input["nonce"]!!.jsonPrimitive.content), op.nonce, name)
            assertContentEquals(b64(expected["sig"]!!.jsonPrimitive.content), op.sig!!, name)
            assertContentEquals(b64(expected["opId"]!!.jsonPrimitive.content), op.opId(crypto), name)
            assertContentEquals(b64(expected["ad"]!!.jsonPrimitive.content), CanonicalCborCodec.encode(op.toAdCbor()), name)
            assertContentEquals(
                b64(expected["signingInput"]!!.jsonPrimitive.content),
                crypto.signingInput(OpEnvelope.DOMAIN, CanonicalCborCodec.encode(op.toUnsignedCbor())),
                name,
            )

            val epochKey = b64(input["epochKey"]!!.jsonPrimitive.content)
            val plaintext = crypto.aeadDecrypt(epochKey, op.nonce, op.ct, CanonicalCborCodec.encode(op.toAdCbor()))
            assertContentEquals(b64(expected["plaintextCbor"]!!.jsonPrimitive.content), plaintext!!, name)
            val body = decodeOpBody(plaintext)
            assertTrue(body is org.squaddle.core.ops.OpBody.IdeaCreate, name)
            assertEquals(input["body"]!!.jsonObject["type"]!!.jsonPrimitive.content, "idea.create", name)
        }
    }

    @Test
    fun requestAuthVectorsVerify() = runTest {
        val crypto = crypto()
        for (vector in vectors("request-auth.json")) {
            val obj = vector.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val input = obj["input"]!!.jsonObject
            val expected = obj["expected"]!!.jsonObject

            val method = input["method"]!!.jsonPrimitive.content
            val pathAndQuery = input["pathAndQuery"]!!.jsonPrimitive.content
            val ts = input["ts"]!!.jsonPrimitive.long
            val body = b64(input["body"]!!.jsonPrimitive.content)
            val device = b64(input["device"]!!.jsonPrimitive.content)

            val signingInput = RequestAuth.signingInput(crypto, method, pathAndQuery, ts, body)
            assertContentEquals(b64(expected["signingInput"]!!.jsonPrimitive.content), signingInput, name)

            val sig = b64(expected["sig"]!!.jsonPrimitive.content)
            assertTrue(crypto.verify(device, signingInput, sig), name)
            assertEquals(expected["header"]!!.jsonPrimitive.content, "SQDL1 device=${input["device"]!!.jsonPrimitive.content}, ts=$ts, sig=${expected["sig"]!!.jsonPrimitive.content}", name)
        }
    }
